import static org.junit.Assert.assertTrue;

/** The Rust that the emitter prints, and the {@code --merged-index} command line.
 * The Rust tests in merged-index-col check that the COL output compiles and
 * agrees byte for byte with the hand-written definition. */
public class MergedIndexRustEmitterTest {
    private static String emit(String sql, String spec) {
        DBSPCompiler compiler = compile(sql);
        ValidatedMergedIndex index = MergedIndexValidator.validate(MergedIndexSpecParser.parse(spec), compiler);
        return MergedIndexRustEmitter.emit(index, compiler, "test.mi");
    }

    private static void assertContains(String text, String... fragments) {
        for (String fragment : fragments)
            assertTrue("missing `" + fragment + "` in:\n" + text, text.contains(fragment));
    }

    /** The text from {@code start} to the next line that is exactly {@code "}"}. */
    private static String item(String text, String start) {
        int from = text.indexOf(start);
        assertTrue("missing `" + start + "`", from >= 0);
        return text.substring(from, text.indexOf("\n}", from));
    }

    @Test
    public void emitsColConstantsAndTrie() {
        String rust = emit(Q3_SCHEMA, COL_SPEC);
        assertContains(rust,
                "generated by the SQL compiler from `test.mi`",
                "pub const TAG_CUSTKEY: u8 = 1;",
                "pub const TAG_ORDERKEY: u8 = 2;",
                "pub const TAG_LINENUMBER: u8 = 3;",
                "pub const INDEX_ID_CUSTOMER_BY_CUSTKEY: u8 = 1;",
                "pub const INDEX_ID_ORDERS_BY_CUSTKEY_ORDERKEY: u8 = 2;",
                "pub const INDEX_ID_LINEITEM_BY_CUSTKEY_ORDERKEY_LINENUMBER: u8 = 3;",
                "name: \"CustomerOrdersLineitem\",",
                "merged_index::ColumnRef { relation: \"Orders\", column: \"o_custkey\" },",
                "payload: merged_index::Payload::All,",
                "merged_index::Via { domain: \"custkey\", relation: \"Orders\" }",
                "merged_index::Payload::Columns(&[\"l_shipdate\", \"l_extendedprice\", \"l_discount\", ])");
    }

    @Test
    public void emitsEachDomainsWidthFromItsRustType() {
        String rust = emit(Q3_SCHEMA, COL_SPEC);
        String domains = rust.substring(rust.indexOf("domains: &["), rust.indexOf("children: &["));
        assertContains(domains, "name: \"custkey\",", "name: \"linenumber\",");
        assertEquals(List.of("i64", "i64", "i32"), widthTypes(domains));
    }

    /** The {@code T} of every {@code width: <T as merged_index::OrderedKey>::WIDTH,} in {@code text}. */
    private static List<String> widthTypes(String text) {
        Matcher matcher = Pattern.compile("width: <(.*) as merged_index::OrderedKey>::WIDTH,").matcher(text);
        List<String> types = new ArrayList<>();
        while (matcher.find())
            types.add(matcher.group(1));
        return types;
    }

    @Test
    public void typesFieldsFromTheSchema() {
        String rust = emit(Q3_SCHEMA, COL_SPEC);
        // custkey comes from Orders.o_custkey through the via.
        assertContains(item(rust, "pub struct LineitemByCustkeyOrderkeyLinenumberKey {"),
                "pub custkey: i64,", "pub orderkey: i64,", "pub linenumber: i32,");
        assertContains(item(rust, "pub struct LineitemByCustkeyOrderkeyLinenumberPayload {"),
                "pub l_shipdate: Date,", "pub l_extendedprice: SqlDecimal<15, 2>,",
                "pub l_discount: SqlDecimal<4, 2>,");
        assertContains(item(rust, "pub struct CustomerByCustkeyPayload {"), "pub c_mktsegment: SqlString,");
    }

    @Test
    public void emitsStraightLineFoldAndUnfold() {
        String rust = emit(Q3_SCHEMA, COL_SPEC);
        assertContains(rust,
                "impl merged_index::MergedIndexDefinition for CustomerOrdersLineitemDefinition {",
                "Key::OrdersByCustkeyOrderkey(k) => merged_index::KeyEncoder::new()"
                        + ".field(TAG_CUSTKEY, &k.custkey).field(TAG_ORDERKEY, &k.orderkey)"
                        + ".finish(INDEX_ID_ORDERS_BY_CUSTKEY_ORDERKEY),",
                "INDEX_ID_CUSTOMER_BY_CUSTKEY => Key::CustomerByCustkey(CustomerByCustkeyKey {",
                "_ => return Err(format!(\"unknown index id {index_id}\")),");
    }

    @Test
    public void emitsTheDefinitionsPayloadDecoderByStreamId() {
        String rust = emit(Q3_SCHEMA, COL_SPEC);
        assertContains(rust,
                "type Payload = Payload;",
                "fn decode_payload(stream_id: u8, bytes: &[u8]) -> Result<Payload, String> {",
                "INDEX_ID_CUSTOMER_BY_CUSTKEY => CustomerByCustkeyPayload::decode(bytes)"
                        + ".map(Payload::CustomerByCustkey),",
                "INDEX_ID_LINEITEM_BY_CUSTKEY_ORDERKEY_LINENUMBER => LineitemByCustkeyOrderkeyLinenumberPayload"
                        + "::decode(bytes).map(Payload::LineitemByCustkeyOrderkeyLinenumber),",
                "_ => Err(format!(\"unknown index id {stream_id}\")),");
    }

    @Test
    public void emitsPayloadCodecInPayloadOrder() {
        String rust = emit(Q3_SCHEMA, COL_SPEC);
        assertContains(rust,
                "merged_index::PayloadEncoder::new().field(&self.l_shipdate).field(&self.l_extendedprice)"
                        + ".field(&self.l_discount).finish()",
                "Key::OrdersByCustkeyOrderkey(_) => OrdersByCustkeyOrderkeyPayload::decode(bytes)"
                        + ".map(Payload::OrdersByCustkeyOrderkey),",
                "| (Key::LineitemByCustkeyOrderkeyLinenumber(_), Payload::LineitemByCustkeyOrderkeyLinenumber(_))");
    }

    @Test
    public void emitsAPrefixPerNodeAndPerChildEdge() {
        String rust = emit(Q3_SCHEMA, COL_SPEC);
        assertContains(rust,
                "pub fn prefix_custkey(custkey: i64, ) -> Vec<u8> {",
                "pub fn prefix_custkey_then_orderkey(custkey: i64, ) -> Vec<u8> {",
                "pub fn prefix_custkey_orderkey(custkey: i64, orderkey: i64, ) -> Vec<u8> {",
                "pub fn prefix_custkey_orderkey_then_linenumber(custkey: i64, orderkey: i64, ) -> Vec<u8> {",
                ".then_tag(TAG_LINENUMBER)",
                "pub fn prefix_custkey_orderkey_linenumber(custkey: i64, orderkey: i64, linenumber: i32, )");
    }

    @Test
    public void siblingNodesGetTheirOwnPrefixesAndVariants() {
        String sql = """
                CREATE TABLE Par (k BIGINT NOT NULL PRIMARY KEY);
                CREATE TABLE Alpha (id BIGINT NOT NULL PRIMARY KEY, k BIGINT NOT NULL, x INT NOT NULL, y INT NOT NULL);
                CREATE TABLE Beta (id BIGINT NOT NULL PRIMARY KEY, k BIGINT NOT NULL, w INT NOT NULL);
                """;
        String spec = """
                domains {
                  root = Par.k, Alpha.k, Beta.k;
                  a = Alpha.id;
                  b = Beta.id;
                }
                merged_index Siblings {
                  root {
                    Par: *;
                    b { Beta: w; }
                    a { Alpha: x, y; }
                  }
                }""";
        String rust = emit(sql, spec);
        // Tags and ids follow the spec's order: the sibling written first comes first.
        assertContains(rust,
                "pub const TAG_ROOT: u8 = 1;",
                "pub const TAG_B: u8 = 2;",
                "pub const TAG_A: u8 = 3;",
                "pub const INDEX_ID_PAR_BY_ROOT: u8 = 1;",
                "pub const INDEX_ID_BETA_BY_ROOT_B: u8 = 2;",
                "pub const INDEX_ID_ALPHA_BY_ROOT_A: u8 = 3;",
                "pub fn prefix_root_then_b(root: i64, )",
                "pub fn prefix_root_then_a(root: i64, )",
                "pub fn prefix_root_b(root: i64, b: i64, )",
                "pub fn prefix_root_a(root: i64, a: i64, )",
                "pub struct SiblingsDefinition;");
        String alpha = item(rust, "pub struct AlphaByRootAPayload {");
        assertTrue(alpha, alpha.indexOf("pub x:") < alpha.indexOf("pub y:"));
    }

    @Test
    public void onePlacementAlwaysMatches() {
        String rust = emit(Q3_SCHEMA, "domains { k = Customer.c_custkey; } merged_index M { k { Customer: *; } }");
        assertContains(rust, "pub fn matches(&self, _key: &Key) -> bool {");
        assertFalse(rust.contains("matches!("));
    }

    @Test
    public void keywordNamesBecomeRawIdentifiers() {
        String rust = emit(Q3_SCHEMA,
                "domains { type = Customer.c_custkey; } merged_index M { type { Customer: *; } }");
        assertContains(rust, "pub const TAG_TYPE: u8 = 1;", "pub r#type: i64,", ".field(TAG_TYPE, &k.r#type)",
                "pub fn prefix_type(r#type: i64, )");
    }

    @Test
    public void rejectsCollidingRustNames() {
        String spec = """
                domains {
                  ab = Customer.c_custkey, Orders.o_custkey;
                  aB = Orders.o_orderkey;
                }
                merged_index M {
                  ab {
                    Customer: *;
                    aB { Orders: o_orderdate, o_shippriority; }
                  }
                }""";
        MergedIndexSpecException exception = assertThrows(MergedIndexSpecException.class,
                () -> emit(Q3_SCHEMA, spec));
        MergedIndexFixtures.assertHasError(exception, 3, "generated Rust name `TAG_AB` is also derived at 2:");
    }

    @Test
    public void rejectsColumnNamesThatAreNotRustFields() {
        String sql = "CREATE TABLE Q (k BIGINT NOT NULL PRIMARY KEY, \"my col\" INT NOT NULL);";
        MergedIndexSpecException exception = assertThrows(MergedIndexSpecException.class,
                () -> emit(sql, "domains { k = Q.k; }\nmerged_index M { k { Q: *; } }"));
        MergedIndexFixtures.assertHasError(exception, 2, "`my col` is not a usable Rust field name");
    }

    // The command line

    private static Path write(String prefix, String suffix, String text) throws IOException {
        Path path = Files.createTempFile(prefix, suffix);
        path.toFile().deleteOnExit();
        Files.writeString(path, text);
        return path;
    }

    @Test
    public void commandLineWritesTheModule() throws Exception {
        Path sql = write("q3", ".sql", Q3_SCHEMA);
        Path spec = write("col", ".mi", COL_SPEC);
        Path output = write("col", ".rs", "");
        CompilerMessages messages = CompilerMain.execute("--noRust", "--merged-index", spec.toString(),
                "--merged-index-output", output.toString(), sql.toString());
        assertEquals(messages.toString(), 0, messages.exitCode);
        assertContains(Files.readString(output), "pub struct CustomerOrdersLineitemDefinition;",
                "from `" + spec.getFileName() + "`");
    }

    @Test
    public void commandLineReportsSpecErrorsWithTheirPositions() throws Exception {
        Path sql = write("q3", ".sql", Q3_SCHEMA);
        Path spec = write("bad", ".mi", COL_SPEC.replace("Orders: o_orderdate", "Orders: o_nosuch"));
        Path output = write("bad", ".rs", "");
        CompilerMessages messages = CompilerMain.execute("--noRust", "--merged-index", spec.toString(),
                "--merged-index-output", output.toString(), sql.toString());
        assertEquals(1, messages.exitCode);
        assertContains(messages.toString(), spec + ":11:", "`Orders` has no column `o_nosuch`");
        assertEquals("", Files.readString(output));
    }

    @Test
    public void commandLineNeedsBothFlags() throws Exception {
        Path sql = write("q3", ".sql", Q3_SCHEMA);
        Path spec = write("col", ".mi", COL_SPEC);
        CompilerMessages messages = CompilerMain.execute("--noRust", "--merged-index", spec.toString(),
                sql.toString());
        assertEquals(1, messages.exitCode);
        assertContains(messages.toString(), "--merged-index and --merged-index-output must be used together");
    }
}
